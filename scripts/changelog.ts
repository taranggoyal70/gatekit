/**
 * Generate CHANGELOG.md from git history.
 *
 *   pnpm changelog
 *
 * The file is generated, never edited by hand: commit messages are the
 * change log, and this only groups them by day, newest first, with a link to
 * each commit. Commits that only regenerate the changelog are left out.
 * Run it before tagging a release or after merging to main.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(__dirname, "..");
const REPO = "https://github.com/taranggoyal70/gatekit";
const SELF = /^Regenerate the changelog\b/;

const raw = execFileSync("git", ["log", "--no-merges", "--date=short", "--format=%ad%x1f%H%x1f%s"], {
  cwd: ROOT,
}).toString();

const byDay = new Map<string, { hash: string; subject: string }[]>();
for (const line of raw.split("\n")) {
  if (!line) continue;
  const [day, hash, subject] = line.split("\x1f") as [string, string, string];
  if (SELF.test(subject)) continue;
  if (!byDay.has(day)) byDay.set(day, []);
  byDay.get(day)!.push({ hash, subject });
}

const escape = (text: string) => text.replace(/([<>*_`[\]])/g, "\\$1");
const linkPullRequests = (text: string) =>
  text.replace(/\\?\(#(\d+)\\?\)/g, (_match, number: string) => `([#${number}](${REPO}/pull/${number}))`);

const out: string[] = [
  "<!-- Generated by `pnpm changelog` (scripts/changelog.ts) from git history. Do not edit by hand. -->",
  "",
  "# Changelog",
  "",
  "Every change to Gatekit, newest first, grouped by the day it was committed.",
  "",
];
for (const [day, commits] of byDay) {
  out.push(`## ${day}`, "");
  for (const { hash, subject } of commits) {
    out.push(`- ${linkPullRequests(escape(subject))} ([\`${hash.slice(0, 7)}\`](${REPO}/commit/${hash}))`);
  }
  out.push("");
}

writeFileSync(path.join(ROOT, "CHANGELOG.md"), out.join("\n"));
console.log(`Wrote CHANGELOG.md: ${[...byDay.values()].flat().length} commits over ${byDay.size} days.`);
